#!/usr/bin/env node
/**
 * Generates packages/reference/data/*.json AND src/generated/catalog-data.ts
 * Run from repo root: node packages/reference/scripts/generate-catalogs.mjs
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '../../..')
const outDir = path.resolve(__dirname, '../data')
const generatedDir = path.resolve(__dirname, '../src/generated')

function slugify(parts) {
  return parts
    .join(' ')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

function writeJson(name, value) {
  fs.writeFileSync(path.join(outDir, name), JSON.stringify(value, null, 2) + '\n')
  console.log(`wrote data/${name}`)
}

fs.mkdirSync(outDir, { recursive: true })
fs.mkdirSync(generatedDir, { recursive: true })

const RELIGIONS = [
  'Hindu', 'Muslim', 'Christian', 'Sikh', 'Jain', 'Buddhist',
  'Parsi', 'Jewish', 'Spiritual', 'No Religion', 'Inter-Religion', 'Other',
].map((label) => ({ slug: slugify([label]), label }))

const MOTHER_TONGUES = [
  'Tamil', 'Telugu', 'Hindi', 'Malayalam', 'Kannada',
  'Marathi', 'Bengali', 'Gujarati', 'Punjabi', 'Urdu',
  'Odia', 'Assamese', 'Konkani', 'Sindhi', 'Tulu',
  'Bhojpuri', 'Marwari', 'Rajasthani', 'Haryanvi', 'Maithili',
  'Dogri', 'Kashmiri', 'Nepali', 'Sourashtra', 'Chhattisgarhi',
  'Garhwali', 'Kumaoni', 'Magahi', 'Manipuri', 'Mizo',
  'Khasi', 'Santhali', 'Kodava', 'Kutchi', 'Himachali',
  'English', 'Other',
].map((label) => ({ slug: slugify([label]), label }))

const RELOCATE = ['Yes', 'No', 'Open to discussion'].map((label) => ({
  slug: slugify([label]),
  label,
}))

const communityMaster = JSON.parse(
  fs.readFileSync(path.join(root, 'packages/database/data/community-master.json'), 'utf8'),
)
const communities = []
const seenCommunity = new Set()
for (const row of communityMaster.communities || []) {
  const religion = String(row.religion || '').trim()
  const label = String(row.name || '').trim()
  if (!religion || !label) continue
  const slug = slugify([religion, label])
  if (seenCommunity.has(slug)) continue
  seenCommunity.add(slug)
  communities.push({
    slug,
    religion,
    label,
    aliases: Array.from(new Set((row.aliases || []).map((a) => String(a).trim()).filter(Boolean))),
  })
}

const locations = JSON.parse(
  fs.readFileSync(path.join(root, 'packages/database/data/india-locations.json'), 'utf8'),
)
const cities = []
const seenCity = new Set()
for (const state of locations.states || []) {
  const stateName = String(state.name || '').trim()
  if (!stateName) continue
  for (const city of state.cities || []) {
    const label = String(city.name || '').trim()
    if (!label) continue
    const slug = slugify([label, stateName])
    if (seenCity.has(slug)) continue
    seenCity.add(slug)
    cities.push({
      slug,
      label,
      state: stateName,
      country: locations.country || 'India',
      aliases: Array.from(new Set((city.aliases || []).map((a) => String(a).trim()).filter(Boolean))),
    })
  }
}

writeJson('religions.json', RELIGIONS)
writeJson('mother-tongues.json', MOTHER_TONGUES)
writeJson('relocate-options.json', RELOCATE)
writeJson('communities.json', { version: 1, communities })
writeJson('cities.json', { version: 1, country: locations.country || 'India', cities })

const ts = `/* AUTO-GENERATED by scripts/generate-catalogs.mjs — do not edit by hand */
import type { CatalogEntry, CityEntry, CommunityEntry } from '../types'

export const RELIGIONS: CatalogEntry[] = ${JSON.stringify(RELIGIONS, null, 2)} as const

export const MOTHER_TONGUES: CatalogEntry[] = ${JSON.stringify(MOTHER_TONGUES, null, 2)} as const

export const RELOCATE_OPTIONS: CatalogEntry[] = ${JSON.stringify(RELOCATE, null, 2)} as const

export const COMMUNITIES: CommunityEntry[] = ${JSON.stringify(communities, null, 2)} as const

export const CITIES: CityEntry[] = ${JSON.stringify(cities, null, 2)} as const

export const CATALOG_COUNTRY = ${JSON.stringify(locations.country || 'India')} as const
`

fs.writeFileSync(path.join(generatedDir, 'catalog-data.ts'), ts)
console.log('wrote src/generated/catalog-data.ts')
console.log(
  `catalogs ready: ${RELIGIONS.length} religions, ${MOTHER_TONGUES.length} tongues, ${communities.length} communities, ${cities.length} cities`,
)
